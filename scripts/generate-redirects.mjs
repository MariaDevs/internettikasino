// Regenerates public/.htaccess for a static export on Apache (Cloudways) from the same
// data next.config.ts uses on Vercel, so the two never drift:
//   src/lib/data/casinos.json          → /go/<slug>/ affiliate redirects
//   src/lib/data/legacy-redirects.json → old WordPress URLs
// Run: npm run redirects
import fs from 'node:fs';

const casinos = JSON.parse(fs.readFileSync('src/lib/data/casinos.json', 'utf8'));
const go = casinos.filter((c) => c.go && c.affiliateUrl).map((c) => [c.go, c.affiliateUrl]);

// Next.js path patterns → Apache regex (leading slash dropped, :path* → .*).
const legacy = JSON.parse(fs.readFileSync('src/lib/data/legacy-redirects.json', 'utf8')).map((r) => [
  r.source
    .slice(1)
    .replace(/\./g, '\\.')
    .replace(/^:path\*\//, '(.+/)?')
    .replace(/\/:path\*/g, '(/.*)?'),
  r.destination,
]);

const esc = (s) => s.replace(/%/g, '\\%');

const htaccess = `Options -MultiViews
RewriteEngine On

# Force HTTPS and the bare domain (canonical host, same as the WordPress site)
RewriteCond %{HTTPS} off [OR]
RewriteCond %{HTTP_HOST} ^www\\. [NC]
RewriteRule ^ https://internettikasino.com%{REQUEST_URI} [L,R=301]

# XML-RPC was a WordPress attack surface; nothing lives there now
RewriteRule ^xmlrpc\\.php$ - [F,L]

# Legacy WordPress URLs → current equivalents (generated by scripts/generate-redirects.mjs)
${legacy.map(([from, to]) => `RewriteRule ^${from}/?$ ${to} [L,R=301]`).join('\n')}

# Affiliate links (/go/<slug>/) — 302 so the target can change without being cached as permanent
${go.map(([slug, url]) => `RewriteRule ^go/${slug}/?$ ${esc(url)} [L,R=302,NE]`).join('\n')}

# Enforce trailing slash on page URLs (matches WordPress + canonical tags)
RewriteCond %{REQUEST_FILENAME} !-f
RewriteCond %{REQUEST_URI} !\\.[a-zA-Z0-9]{2,5}$
RewriteCond %{REQUEST_URI} !/$
RewriteRule ^(.*)$ /$1/ [L,R=301]

# 404 fallback
ErrorDocument 404 /404.html

<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresByType image/png "access plus 1 year"
  ExpiresByType image/jpeg "access plus 1 year"
  ExpiresByType image/webp "access plus 1 year"
  ExpiresByType image/svg+xml "access plus 1 year"
  ExpiresByType font/woff2 "access plus 1 year"
  ExpiresByType text/css "access plus 1 year"
  ExpiresByType application/javascript "access plus 1 year"
  ExpiresByType text/html "access plus 1 hour"
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css application/javascript application/json image/svg+xml text/xml application/xml
</IfModule>

<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  Header always set X-Frame-Options "DENY"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  <FilesMatch "^go">
    Header set X-Robots-Tag "noindex, nofollow"
  </FilesMatch>
</IfModule>
`;
fs.writeFileSync('public/.htaccess', htaccess);


console.log(`.htaccess: ${go.length} affiliate redirects, ${legacy.length} legacy redirects`);
