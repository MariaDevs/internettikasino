// Regenerates public/.htaccess (Cloudways/Apache) and vercel.json from the casino data,
// so /go/<slug>/ affiliate redirects never drift from src/lib/data/casinos.json.
// Run: npm run redirects
import fs from 'node:fs';

const casinos = JSON.parse(fs.readFileSync('src/lib/data/casinos.json', 'utf8'));
const go = casinos.filter((c) => c.go && c.affiliateUrl).map((c) => [c.go, c.affiliateUrl]);

// Old WordPress URLs that should keep their equity.
const legacy = [
  ['go/casinofriday', '/go/casino-friday/'],
  ['list/top-rated', '/parhaat-kasinot/'],
  ['list/.*', '/parhaat-kasinot/'],
  ['kierratysvapaat-bonukset', '/ilmaiskierrokset/'],
  ['kierratysvapaat-ilmaiskierrokset', '/ilmaiskierrokset/'],
  ['nettikasino-ilman-rekisteroitymista', '/kasino-ilman-rekisteroitymista/'],
  ['paras-nettikasino', '/parhaat-kasinot/'],
  ['parhaat-nettikasinot', '/parhaat-kasinot/'],
  ['homepage', '/'],
  ['feed', '/'],
  ['slider/.*', '/'],
  ['category/uncategorized', '/category/oppaat/'],
];

const esc = (s) => s.replace(/%/g, '\\%');

const htaccess = `Options -MultiViews
RewriteEngine On

# Force HTTPS and the bare domain (canonical host, same as the WordPress site)
RewriteCond %{HTTPS} off [OR]
RewriteCond %{HTTP_HOST} ^www\\. [NC]
RewriteRule ^ https://internettikasino.com%{REQUEST_URI} [L,R=301]

# Old WordPress endpoints with no static equivalent
RewriteRule ^wp-(admin|login\\.php|json)(/.*)?$ / [L,R=301]
RewriteRule ^xmlrpc\\.php$ - [F,L]
RewriteRule ^(.+/)?feed/?$ / [L,R=301]

# Legacy WordPress URLs → current equivalents (generated by scripts/generate-redirects.mjs)
${legacy.map(([from, to]) => `RewriteRule ^${from}/?$ ${to} [L,R=301]`).join('\n')}

# Affiliate links (/go/<slug>/) — 302 so the target can change without being cached as permanent
${go.map(([slug, url]) => `RewriteRule ^go/${slug}/?$ ${esc(url)} [L,R=302,NE]`).join('\n')}

# Enforce trailing slash on page URLs (matches WordPress + canonical tags)
RewriteCond %{REQUEST_FILENAME} !-f
RewriteCond %{REQUEST_URI} !\\.[a-zA-Z0-9]{2,5}$
RewriteCond %{REQUEST_URI} !/$
RewriteRule ^(.*)$ /$1/ [L,R=301]

# 404 fallback
ErrorDocument 404 /404.html

<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresByType image/png "access plus 1 year"
  ExpiresByType image/jpeg "access plus 1 year"
  ExpiresByType image/webp "access plus 1 year"
  ExpiresByType image/svg+xml "access plus 1 year"
  ExpiresByType font/woff2 "access plus 1 year"
  ExpiresByType text/css "access plus 1 year"
  ExpiresByType application/javascript "access plus 1 year"
  ExpiresByType text/html "access plus 1 hour"
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css application/javascript application/json image/svg+xml text/xml application/xml
</IfModule>

<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  Header always set X-Frame-Options "DENY"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  <FilesMatch "^go">
    Header set X-Robots-Tag "noindex, nofollow"
  </FilesMatch>
</IfModule>
`;
fs.writeFileSync('public/.htaccess', htaccess);

const vercel = {
  framework: 'nextjs',
  trailingSlash: true,
  headers: [
    {
      source: '/(.*)',
      headers: [
        { key: 'X-Content-Type-Options', value: 'nosniff' },
        { key: 'X-Frame-Options', value: 'DENY' },
        { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
      ],
    },
    { source: '/images/(.*)', headers: [{ key: 'Cache-Control', value: 'public, max-age=31536000, immutable' }] },
    { source: '/go/(.*)', headers: [{ key: 'X-Robots-Tag', value: 'noindex, nofollow' }] },
  ],
  redirects: [
    { source: '/:path*', has: [{ type: 'host', value: 'www.internettikasino.com' }], destination: 'https://internettikasino.com/:path*', permanent: true },
    ...legacy.map(([from, to]) => ({ source: '/' + from.replace('.*', ':path*'), destination: to, permanent: true })),
    ...go.map(([slug, url]) => ({ source: `/go/${slug}`, destination: url, permanent: false })),
  ],
};
fs.writeFileSync('vercel.json', JSON.stringify(vercel, null, 2) + '\n');

console.log(`.htaccess + vercel.json: ${go.length} affiliate redirects, ${legacy.length} legacy redirects`);
